def _fmt_date(d: str) -> str:
    y, m, day = map(int, d.split("-"))
    months = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября", "ноября", "декабря"]
    return f"{day} {months[m - 1]} {y}"


def index_html() -> str:
    cards = "".join(
        f'<article class="card"><h2><a href="/blog/{a["slug"]}">{escape(a["title"])}</a></h2><p>{escape(a["description"])}</p>'
        f'<div class="meta">{_fmt_date(a["date"])} · {a["read"]} мин чтения</div></article>' for a in sorted(ARTICLES, key=lambda x: x["date"], reverse=True))
    body = f'<h1>Блог «{SITE}»</h1><p class="lead">Практические материалы для владельцев мини-гостиниц и посуточной аренды: площадки, цены, учёт, заселение.</p><div class="list">{cards}</div>'
    return _wrap(f"Блог — {SITE}: управление бронированиями и посуточной арендой", "Статьи о синхронизации площадок, расчёте прибыли, прямых бронированиях и автоматизации гостиницы.",
                 f"{config.PUBLIC_BASE_URL}/blog/", body)


def article_html(slug: str) -> str | None:
    a = next((x for x in ARTICLES if x["slug"] == slug), None)
    if not a:
        return None
    url = f"{config.PUBLIC_BASE_URL}/blog/{a['slug']}"
    import json
    ld = '<script type="application/ld+json">' + json.dumps({"@context": "https://schema.org", "@type": "Article", "headline": a["title"], "datePublished": a["date"],
                                                             "description": a["description"], "mainEntityOfPage": url, "publisher": {"@type": "Organization", "name": SITE}},
                                                            ensure_ascii=False) + "</script>\n"
    others = "".join(f'<li><a href="/blog/{x["slug"]}">{escape(x["title"])}</a></li>' for x in ARTICLES if x["slug"] != slug)[:3000]
    body = (f'<p class="crumbs"><a href="/blog/">← Все статьи</a></p><article><h1>{escape(a["title"])}</h1>'
            f'<div class="meta">{_fmt_date(a["date"])} · {a["read"]} мин чтения</div>{a["body"]}</article>'
            f'<div class="cta"><b>Попробуйте «{SITE}» бесплатно 14 дней</b><p>Шахматка, синхронизация площадок, автопилот и отчёты — на любом тарифе.</p><a class="btn" href="/app/#register">Создать аккаунт</a></div>'
            f'<h2>Читайте также</h2><ul class="more">{others}</ul>')
    return _wrap(f"{a['title']} — {SITE}", a["description"], url, body, ld)


